-- 4. ORDERS & ORDER ITEMS TABLE
-- ==============================================================================
create table if not exists public.orders (
  id text primary key,
  user_id uuid references auth.users(id) on delete set null,
  customer_email text,
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'shipping', 'completed', 'cancelled', 'return_requested', 'refunded')),
  shipping_name text not null,
  shipping_phone text not null,
  shipping_address text not null,
  shipping_note text,
  payment_method text not null default 'cod' check (payment_method in ('vietqr', 'cod')),
  tracking_code text,
  shipping_carrier text default 'Giao Hàng Nhanh',
  return_reason text,
  return_note text,
  admin_refund_note text,
  returned_at timestamptz,
  total bigint not null default 0,
  created_at timestamptz not null default timezone('utc'::text, now())
);

-- Ensure shipping, tracking and refund columns exist for existing tables
alter table public.orders add column if not exists tracking_code text;
alter table public.orders add column if not exists shipping_carrier text default 'Giao Hàng Nhanh';
alter table public.orders add column if not exists return_reason text;
alter table public.orders add column if not exists return_note text;
alter table public.orders add column if not exists admin_refund_note text;
alter table public.orders add column if not exists returned_at timestamptz;

-- Order Items Table
create table if not exists public.order_items (
  id bigint primary key generated by default as identity,
  order_id text not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  product_price bigint not null default 0,
  quantity int not null default 1,
  primary_image text,
  created_at timestamptz not null default timezone('utc'::text, now())
);

-- Enable RLS
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Policies for orders
drop policy if exists "Orders readable by owner or admin" on public.orders;
create policy "Orders readable by owner or admin"
  on public.orders for select
  using (
    auth.uid() = user_id
    or auth.jwt()->>'email' = customer_email
    or exists (select 1 from public.profiles where profiles.id = auth.uid() and profiles.role = 'admin')
    or user_id is null
  );

drop policy if exists "Users can insert orders" on public.orders;
create policy "Users can insert orders"
  on public.orders for insert
  with check (true);

drop policy if exists "Orders updatable by admin or pending owner" on public.orders;
create policy "Orders updatable by admin or pending owner"
  on public.orders for update
  using (
    exists (select 1 from public.profiles where profiles.id = auth.uid() and profiles.role = 'admin')
    or (auth.uid() = user_id and status in ('pending', 'completed', 'return_requested'))
  );

-- Policies for order_items
drop policy if exists "Order items viewable with order" on public.order_items;
create policy "Order items viewable with order"
  on public.order_items for select
  using (
    exists (
      select 1 from public.orders
      where orders.id = order_items.order_id
        and (
          orders.user_id = auth.uid()
          or orders.customer_email = auth.jwt()->>'email'
          or exists (select 1 from public.profiles where profiles.id = auth.uid() and profiles.role = 'admin')
          or orders.user_id is null
        )
    )
  );

drop policy if exists "Order items insertable" on public.order_items;
create policy "Order items insertable"
  on public.order_items for insert
  with check (true);

